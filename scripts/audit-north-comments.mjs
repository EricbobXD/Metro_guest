import {writeFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
import {buildNorthMap} from '../src/north-map-model.js';
import {createNorthSvg} from '../src/north-map-svg.js';
import {commentReferenceLayout} from '../src/north-map-comment-reference.js';
const m=buildNorthMap(),p=id=>m.byId.get(id),before=commentReferenceLayout.positions;
const d=(a,b)=>Math.hypot(a.x-b.x,a.y-b.y),gap=(a,b)=>d(p(a),p(b)),old=(a,b)=>d(before[a],before[b]);
const doc=new JSDOM(createNorthSvg(m),{contentType:'image/svg+xml'}).window.document;
const checks=[];const check=(comment,description,pass,evidence)=>checks.push({comment,description,pass:!!pass,evidence});
const smaller=(a,b)=>gap(a,b)<old(a,b),larger=(a,b)=>gap(a,b)>old(a,b),near=(a,b)=>Math.abs(a-b)<1e-4;
check(1,'象山終段與前方等距',near(gap('象山','廣慈/奉天宮'),gap('台北101/世貿','象山')),gap('象山','廣慈/奉天宮'));
const ng=doc.querySelector('[data-label="南港"]'),ngBox=m.labels.find(l=>l.name==='南港');
check(2,'南港名稱置中，名稱及轉乘下移',ng.getAttribute('text-anchor')==='middle'&&near(+ng.getAttribute('x'),p('南港').x)&&ngBox.y>p('南港').y);
check(3,'BL19—BL21 縮短',smaller('永春','後山埤')&&smaller('後山埤','昆陽'));
check(4,'西門站體上移',p('西門').y<before['西門'].y,{before:before['西門'].y,after:p('西門').y});
check(5,'BL08—BL09 加長',larger('新埔','江子翠'),{before:old('新埔','江子翠'),after:gap('新埔','江子翠')});
check(6,'龍山寺站體上移',p('龍山寺').y<before['龍山寺'].y);
const a03=m.labels.find(l=>l.stationIds[0]==='新北產業園區〔A〕');
check(7,'共享站名位於 A03 上方',a03?.side==='above'&&a03.y+a03.h<p('新北產業園區〔A〕').y);
check(8,'A03 與 A02 同高',near(p('新北產業園區〔A〕').y,p('三重').y));
const airport=m.routes.find(r=>r.id==='A-0'),index=airport.pathPoints.findIndex(n=>n.id==='三重');
check(9,'A02 左右中點水平接線',near(airport.pathPoints[index-1].y,p('三重').y)&&near(airport.pathPoints[index+1].y,p('三重').y));
check(10,'移除機捷三重重複站名',!doc.querySelector('[data-label-group="三重〔A〕"]')&&doc.querySelectorAll('[data-label="三重"]').length===1);
const ding=m.labels.find(l=>l.name==='頂埔');
check(11,'頂埔字樣上移',ding.y+ding.h<p('頂埔').y);
check(12,'A15—A23 縮短',smaller('大園','中壢車站'),{before:old('大園','中壢車站'),after:gap('大園','中壢車站')});
check(13,'圖示小碧潭支線改黃綠',m.routes.find(r=>r.id==='G-1').color==='#B4CA45');
check(14,'Y11—Y10 加長',larger('景安','景平'));
check(15,'Y08—Y07 縮短',smaller('十四張','大坪林'));
const taipei=doc.querySelector('[data-label-group="台北車站"]');
const yOf=n=>+n.getAttribute('transform').match(/,([\d.-]+)\)/)[1];
check(16,'台北車站機捷提示列於鐵路提示下方',yOf(taipei.querySelector('[data-metro-transfer]'))>yOf(taipei.querySelector('[data-rail-transfer]')));
const central=[['民權西路','中山國小'],['中山','松江南京'],['台北車站','忠孝新生'],['中正紀念堂','東門']];
check(17,'指定四段同步縮短',central.every(([a,b])=>smaller(a,b)),central.map(([a,b])=>({from:a,to:b,before:old(a,b),after:gap(a,b)})));
check(18,'BR11—BR14 加長',larger('南京復興','大直'));
check(19,'淡海所有分支同主線色',new Set(m.routes.filter(r=>r.system==='V').map(r=>r.color)).size===1);
const orange=['菜寮','三重','先嗇宮','頭前庄','新莊','輔大','丹鳳','迴龍'],orangeGaps=orange.slice(1).map((n,i)=>gap(orange[i],n));
check(20,'O14—O21 近似等距並保留 BL/Y 軸向',Math.max(...orangeGaps)-Math.min(...orangeGaps)<1,orangeGaps);
const overlaps=(a,b)=>a.x<b.x+b.w&&a.x+a.w>b.x&&a.y<b.y+b.h&&a.y+a.h>b.y;
let labelOverlaps=[];for(let i=0;i<m.labels.length;i++)for(let j=i+1;j<m.labels.length;j++)if(overlaps(m.labels[i],m.labels[j]))labelOverlaps.push([m.labels[i].name,m.labels[j].name]);
const report={checks,passed:checks.filter(c=>c.pass).length,total:checks.length,labelCount:m.labels.length,labelOverlaps,topology:{stations:m.stations.length,codes:m.stations.reduce((n,s)=>n+s.codes.length,0),walks:m.walks.length},deformation:Object.fromEntries(['BL','Y'].map(system=>[system,Math.max(...m.stations.filter(s=>s.systems.includes(system)).map(s=>d(s,before[s.id])))]))};
writeFileSync('docs/north-map-comment-audit.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));if(report.passed!==20||labelOverlaps.length)process.exitCode=1;

